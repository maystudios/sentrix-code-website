"""Write src/components/brand/figures.ts and pixel-icons.ts and render a preview sheet.

Usage: python scripts/pixel-art/build.py [PREVIEW_DIR]
"""

import json
import re
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
from figures import FIGURES, load  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
ICONS = ["idea", "concept", "prototype", "design", "code", "test", "rocket", "chip", "server", "phone", "gamepad", "robot"]


def runs(cells):
    """Horizontal runs per row and colour: [x, y, length, letter]."""
    result = []
    for (x, y), letter in sorted(cells.items(), key=lambda item: (item[0][1], item[0][0])):
        last = result[-1] if result else None
        if last and last[1] == y and last[0] + last[2] == x and last[3] == letter:
            last[2] += 1
        else:
            result.append([x, y, 1, letter])
    return result


def used_palette(palette, cell_sets):
    used = {ch for cells in cell_sets for ch in cells.values()}
    return {letter: colour for letter, colour in palette.items() if letter in used}


def frame_group(name):
    match = re.match(r"^(.*\D)(\d+)$", name)
    return (match.group(1), int(match.group(2))) if match else (None, None)


def render(figure, names, scale):
    image = Image.new("RGBA", (figure["width"] * scale, figure["height"] * scale), (0, 0, 0, 0))
    for name in names:
        for (x, y), letter in figure["layers"][name].items():
            colour = figure["palette"][letter]
            rgb = tuple(int(colour[i : i + 2], 16) for i in (1, 3, 5))
            image.paste((*rgb, 255), (x * scale, y * scale, (x + 1) * scale, (y + 1) * scale))
    return image


def main():
    data = {}
    for name, figure in FIGURES.items():
        data[name] = {
            "width": figure["width"],
            "height": figure["height"],
            "palette": used_palette(figure["palette"], figure["layers"].values()),
            "layers": {layer: runs(cells) for layer, cells in figure["layers"].items()},
        }
    target = ROOT / "src/components/brand/figures.ts"
    target.write_text(
        "// Generated by scripts/pixel-art/build.py from scripts/pixel-art/figures.py. Do not edit.\n"
        "// Pixel-perfect rebuilds of generated images, split into layers: runs of [x, y, length, letter].\n"
        'import type { PixelFigureData } from "./PixelArt";\n\n'
        f"export const FIGURES = {json.dumps(data, separators=(',', ':'))} satisfies Record<string, PixelFigureData>;\n",
        encoding="utf-8",
    )
    icons = {}
    for name in ICONS:
        grid = load(f"icon-{name}")
        icons[name] = {
            "width": grid["width"],
            "height": grid["height"],
            "palette": used_palette(grid["palette"], [grid["cells"]]),
            "layers": {"base": runs(grid["cells"])},
        }
    (ROOT / "src/components/brand/pixel-icons.ts").write_text(
        "// Generated by scripts/pixel-art/build.py from scripts/pixel-art/grids/icon-*.txt. Do not edit.\n"
        "// Pixel-perfect rebuilds of generated icons (docs/provenance.md).\n"
        'import type { PixelFigureData } from "./PixelArt";\n'
        'import type { IconName } from "@/content/types";\n\n'
        f"export const ICONS = {json.dumps(icons, separators=(',', ':'))} satisfies Record<IconName, PixelFigureData>;\n",
        encoding="utf-8",
    )
    print("wrote figures.ts and pixel-icons.ts")

    if len(sys.argv) < 2:
        return
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    tiles = []
    for name, figure in FIGURES.items():
        groups = {}
        for layer in figure["layers"]:
            group, index = frame_group(layer)
            if group:
                groups.setdefault(group, []).append(layer)
        plain = [layer for layer in figure["layers"] if not frame_group(layer)[0]]
        first = [sorted(frames)[0] for frames in groups.values()]
        tiles.append(render(figure, plain + first, 6))
        for group, frames in groups.items():
            for frame in sorted(frames)[1:]:
                others = [sorted(f)[0] for g, f in groups.items() if g != group]
                tiles.append(render(figure, plain + others + [frame], 4))
    width = 1900
    x = y = 12
    row_height = 0
    sheet = Image.new("RGBA", (width, 2400), (11, 15, 23, 255))
    for tile in tiles:
        if x + tile.width > width - 12:
            x = 12
            y += row_height + 16
            row_height = 0
        sheet.alpha_composite(tile, (x, y))
        x += tile.width + 20
        row_height = max(row_height, tile.height)
    sheet.crop((0, 0, width, y + row_height + 12)).save(out / "figures.png")
    print("preview", out / "figures.png")


if __name__ == "__main__":
    main()
