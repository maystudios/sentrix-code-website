"""Rasterise the Sentrix pictogram into a block grid for the footer.

Writes src/components/brand/pixel-logo-data.ts. Re-run after changing COLUMNS or the paths.
The chevron's small rounded tip is approximated by straight edges.
"""

from PIL import Image, ImageDraw

COLUMNS = 48
VIEW_W, VIEW_H = 233.0, 140.0  # pictogram extent incl. the 1.04 shift of the x

CHEVRON = [(97.656, 20.5), (74.344, 20.5), (11.335, 66.366), (10.0, 70.0), (11.335, 73.634),
           (74.344, 119.5), (97.656, 119.5), (22.037, 75.546), (22.037, 64.454)]
X_A = [(126.777, 20.5), (222.666, 119.5), (204.139, 119.5), (165.387, 79.617), (126.777, 119.5),
       (108.25, 119.5), (156.194, 70.0), (108.25, 20.5)]
X_B = [(204.139, 20.5), (222.666, 20.5), (179.530, 64.909), (170.337, 55.433)]

SCALE = 8
cell = VIEW_W / COLUMNS
rows = round(VIEW_H / cell)
canvas = Image.new("L", (COLUMNS * SCALE, rows * SCALE), 0)
draw = ImageDraw.Draw(canvas)
for shape, value in ((CHEVRON, 1), (X_A, 2), (X_B, 2)):
    draw.polygon([(x / cell * SCALE, y / cell * SCALE) for x, y in shape], fill=value * 120)

cells = []
for row in range(rows):
    for column in range(COLUMNS):
        block = canvas.crop((column * SCALE, row * SCALE, (column + 1) * SCALE, (row + 1) * SCALE))
        values = list(block.tobytes())
        filled = [v for v in values if v > 0]
        if len(filled) >= len(values) * 0.34:
            cells.append((column, row, 1 if max(filled) <= 120 else 2))

top = min(r for _, r, _ in cells)
bottom = max(r for _, r, _ in cells)
left = min(c for c, _, _ in cells)
right = max(c for c, _, _ in cells)
cells = [(c - left, r - top, k) for c, r, k in cells]
with open("src/components/brand/pixel-logo-data.ts", "w", encoding="utf-8") as handle:
    handle.write("// Generated by scripts/build-pixel-logo.py. Do not edit by hand.\n")
    handle.write("// Each cell: [column, row, part] with part 1 = chevron, 2 = x.\n")
    handle.write(f"export const PIXEL_LOGO_COLUMNS = {right - left + 1};\n")
    handle.write(f"export const PIXEL_LOGO_ROWS = {bottom - top + 1};\n")
    handle.write("export const PIXEL_LOGO_CELLS: [number, number, number][] = [\n")
    for c, r, k in cells:
        handle.write(f"  [{c}, {r}, {k}],\n")
    handle.write("];\n")
print(f"{len(cells)} cells, {right - left + 1} x {bottom - top + 1}")
for r in range(bottom - top + 1):
    print("".join({1: "#", 2: "x"}.get(next((k for c, rr, k in cells if c == col and rr == r), 0), ".") for col in range(right - left + 1)))
